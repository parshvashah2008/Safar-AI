const DEFAULT_TRAVEL_IMAGE =
  'https://images.unsplash.com/photo-1488646953014-85cb44e25828?auto=format&fit=crop&w=1200&q=80';

export function getDestinationImage(nameOrCountry?: string | null): string {
  if (!nameOrCountry) return DEFAULT_TRAVEL_IMAGE;
  const clean = nameOrCountry.toLowerCase().replace(/[^a-z]/g, '');
  for (const [key, url] of Object.entries(DESTINATION_IMAGES)) {
    if (clean.includes(key) || key.includes(clean)) {
      return url;
    }
  }
  return DEFAULT_TRAVEL_IMAGE;
}
